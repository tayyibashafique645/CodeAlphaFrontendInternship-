function openTask(taskName) {

    if (taskName === "gallery") {
        window.location.href = "gallery/gallery.html";
    }

    else if (taskName === "calculator") {
        window.location.href = "calculator/calculator.html";
    }

    else if (taskName === "portfolio") {
        window.location.href = "portfolio/portfolio.html";
    }

    else if (taskName === "music-player") {
        window.location.href = "music-player/music.html";
    }

}